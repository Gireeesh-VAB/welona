/**
 * Dummy data for the Admin → Reports → Sales → Sales Report screen.
 *
 * Branch names and category names line up with the rows seeded by
 * `prisma/seed-admin-showcase.ts`, so the branch / category dropdowns on the
 * page filter this list in a sensible way out of the box.
 *
 * All money is stored as integer paise (minor units).
 */

export interface SalesReportRow {
  bNo: string;
  joinedDate: string;       // ISO yyyy-mm-dd
  receiptNumber: string;
  receiptDate: string;      // ISO yyyy-mm-dd
  clientName: string;
  mobileNumber: string;
  packageDetails: string;
  category: string;         // Must match a Category.name from the seed
  branchName: string;       // Must match a Branch.name from the seed
  mediaName: string;
  callType: string;
  packageAmount: number;    // paise
  taxAmount: number;        // paise
  cash: number;
  creditCards: number;
  officeScan: number;
  cheque: number;
  bajaj: number;
  ezFinanz: number;
  saveIn: number;
  shopse: number;
  fibe: number;
  paidAmount: number;       // paise — sum of the 9 payment columns
  balanceAmount: number;    // paise — packageAmount + taxAmount - paidAmount
}

/** Convenience helper: build a row whose paidAmount + balanceAmount line up. */
function row(
  fields: Omit<SalesReportRow, 'paidAmount' | 'balanceAmount'>,
): SalesReportRow {
  const paid =
    fields.cash + fields.creditCards + fields.officeScan + fields.cheque +
    fields.bajaj + fields.ezFinanz + fields.saveIn + fields.shopse + fields.fibe;
  return {
    ...fields,
    paidAmount: paid,
    balanceAmount: Math.max(0, fields.packageAmount + fields.taxAmount - paid),
  };
}

